test('login rejects invalid form locally and persists a valid server session', async () => {
  const register = jest.fn();
  await render(<LoginScreen onGoToRegister={register} />);
  await fireEvent.press(screen.getByTestId('login-submit'));
  expect(Alert.alert).toHaveBeenCalled(); expect(axiosClient.post).not.toHaveBeenCalled();
  await fireEvent.changeText(screen.getByTestId('login-email'), ' qa@shopai.test ');
  await fireEvent.changeText(screen.getByTestId('login-password'), 'test-password');
  (axiosClient.post as jest.Mock).mockResolvedValueOnce({data: {accessToken: 'server-jwt', user: {id: 'qa', email: 'qa@shopai.test', name: 'QA'}}});
  await fireEvent.press(screen.getByTestId('login-submit'));
  await waitFor(() => expect(useAuthStore.getState().token).toBe('server-jwt'));
  expect(axiosClient.post).toHaveBeenCalledWith('/api/auth/login', {email: 'qa@shopai.test', password: 'test-password'});
  await fireEvent.press(screen.getByText(/\u0110\u0103ng k\u00fd ngay/)); expect(register).toHaveBeenCalled();
});
test('registration prevents mismatched passwords and sends the validated form', async () => {
  await render(<RegisterScreen onGoToLogin={jest.fn()} onRegisterSuccess={jest.fn()} />);
  await fireEvent.press(screen.getByRole('button', {name: 'T\u1ea1o t\u00e0i kho\u1ea3n'}));
  expect(Alert.alert).toHaveBeenCalled();
  await fireEvent.changeText(screen.getByPlaceholderText('Nguy\u1ec5n V\u0103n A'), ' QA User ');
  await fireEvent.changeText(screen.getByPlaceholderText('example@gmail.com'), ' qa@shopai.test ');
  await fireEvent.changeText(screen.getByPlaceholderText('T\u1ed1i thi\u1ec3u 6 k\u00fd t\u1ef1'), 'test-password');
  await fireEvent.changeText(screen.getByPlaceholderText('Nh\u1eadp l\u1ea1i m\u1eadt kh\u1ea9u'), 'different-password');
  await fireEvent.press(screen.getByRole('button', {name: 'T\u1ea1o t\u00e0i kho\u1ea3n'}));
  expect(axiosClient.post).not.toHaveBeenCalled();
  await fireEvent.changeText(screen.getByPlaceholderText('Nh\u1eadp l\u1ea1i m\u1eadt kh\u1ea9u'), 'test-password');
  (axiosClient.post as jest.Mock).mockResolvedValueOnce({data: {accessToken: 'registration-jwt', user: {id: 'qa', email: 'qa@shopai.test', name: 'QA User'}}});
  await fireEvent.press(screen.getByRole('button', {name: 'T\u1ea1o t\u00e0i kho\u1ea3n'}));
  await waitFor(() => expect(useAuthStore.getState().token).toBe('registration-jwt'));
  expect(axiosClient.post).toHaveBeenCalledWith('/api/auth/register', {name: 'QA User', email: 'qa@shopai.test', password: 'test-password'});
});
